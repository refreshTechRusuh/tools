#!/usr/bin/env bash
# ============================================================
# test_integration.sh — End-to-End Integration Test BE-1 <-> BE-2
# Covers tasks-integration.md INT-6
#
# Prasyarat (semua service harus running):
#   BE-1: user-service (:8086), queue-service (:8084), dukcapil-mock (:8085)
#   BE-2: event-service (:8082), booking-service (:8081), payment-service (:8083)
#         worker-service (background, pantau Kafka log)
#
# Jalankan: chmod +x test_integration.sh && ./test_integration.sh
# ============================================================

set -euo pipefail

# ─────────────────────────────────────────────────────────────
# Config — sesuaikan jika port atau credential berbeda
# ─────────────────────────────────────────────────────────────
USER_SVC="http://localhost:8086"
QUEUE_SVC="http://localhost:8084"
EVENT_SVC="http://localhost:8082"
BOOKING_SVC="http://localhost:8081"
PAYMENT_SVC="http://localhost:8083"

# Credential admin (bootstrap dari ADMIN_EMAIL / ADMIN_PASSWORD di user-service)
# Ganti jika env user-service pakai nilai berbeda
ADMIN_EMAIL="${ADMIN_EMAIL:-admin@rusuh.com}"
ADMIN_PASSWORD="${ADMIN_PASSWORD:-admin123}"

# NIK yang valid di dukcapil-mock BE-1 (harus ada di tabel residents)
# Sesuaikan dengan seed data yang ada di dukcapil-mock/migrations/
TEST_NIK="${TEST_NIK:-3273000000000001}"
TEST_NAMA="${TEST_NAMA:-Budi Santoso}"
TEST_TGL_LAHIR="${TEST_TGL_LAHIR:-1990-01-01}"
TEST_NAMA_IBU="${TEST_NAMA_IBU:-Siti Aminah}"

# Email user reguler untuk test booking
USER_EMAIL="testuser_$(date +%s)@rusuh.com"
USER_PASSWORD="Test12345!"

# ─────────────────────────────────────────────────────────────
# Warna dan helper
# ─────────────────────────────────────────────────────────────
GREEN="\033[32m"
RED="\033[31m"
YELLOW="\033[33m"
CYAN="\033[36m"
BOLD="\033[1m"
RESET="\033[0m"

PASS=0
FAIL=0

step() { echo -e "\n${BOLD}${CYAN}━━━ STEP $1: $2 ━━━${RESET}"; }
ok()   { echo -e "${GREEN}✅ $1${RESET}"; PASS=$((PASS+1)); }
fail() { echo -e "${RED}❌ $1${RESET}"; FAIL=$((FAIL+1)); }
info() { echo -e "${YELLOW}ℹ  $1${RESET}"; }

# Ambil field dari JSON response
jq_get() { echo "$1" | python3 -c "import sys,json; d=json.load(sys.stdin); print($2)" 2>/dev/null || echo ""; }
# Cek status "00000" (sukses)
assert_ok() {
  local resp="$1" label="$2"
  local status
  status=$(jq_get "$resp" "d.get('status','?')")
  if [[ "$status" == "00000" ]]; then
    ok "$label (status=$status)"
  else
    fail "$label (status=$status, resp=$(echo "$resp" | head -c 200))"
  fi
}

# ─────────────────────────────────────────────────────────────
# Preflight: cek semua service health
# ─────────────────────────────────────────────────────────────
step "0" "Health check semua service"

check_health() {
  local name="$1" url="$2"
  local resp
  resp=$(curl -sf "$url/sys/ping" 2>/dev/null || echo '{"status":"ERROR"}')
  local status
  status=$(jq_get "$resp" "d.get('status','ERROR')")
  if [[ "$status" == "00000" ]]; then
    ok "$name UP ($url)"
  else
    fail "$name DOWN ($url) — pastikan service sudah running"
  fi
}

check_health "user-service"    "$USER_SVC"
check_health "queue-service"   "$QUEUE_SVC"
check_health "event-service"   "$EVENT_SVC"
check_health "booking-service" "$BOOKING_SVC"
check_health "payment-service" "$PAYMENT_SVC"

if [[ $FAIL -gt 0 ]]; then
  echo -e "\n${RED}${BOLD}Preflight gagal: $FAIL service tidak merespons. Hentikan test.${RESET}"
  exit 1
fi

# ─────────────────────────────────────────────────────────────
# STEP 1: Admin login via user-service → dapat authToken
# ─────────────────────────────────────────────────────────────
step "1" "Admin login via user-service"

ADMIN_LOGIN=$(curl -sf -X POST "$USER_SVC/auth/login" \
  -H "Content-Type: application/json" \
  -d "{\"email\":\"$ADMIN_EMAIL\",\"password\":\"$ADMIN_PASSWORD\"}" 2>/dev/null \
  || echo '{"status":"ERROR"}')

assert_ok "$ADMIN_LOGIN" "Admin login"

ADMIN_TOKEN=$(jq_get "$ADMIN_LOGIN" "d.get('data',{}).get('authToken','')")
if [[ -z "$ADMIN_TOKEN" ]]; then
  fail "authToken admin tidak ditemukan di response"
  info "Response: $ADMIN_LOGIN"
  info "Cek ADMIN_EMAIL dan ADMIN_PASSWORD di env user-service"
  exit 1
fi
info "Admin token prefix: ${ADMIN_TOKEN:0:20}..."

# ─────────────────────────────────────────────────────────────
# STEP 2: Admin buat event baru via event-service
# ─────────────────────────────────────────────────────────────
step "2" "Admin buat event + kategori (event-service)"

CREATE_EVENT=$(curl -sf -X POST "$EVENT_SVC/api/event/v1/admin/create-event" \
  -H "Content-Type: application/json" \
  -H "Authorization: Bearer $ADMIN_TOKEN" \
  -d '{
    "name": "Integration Test Concert '"$(date +%s)"'",
    "description": "Auto-generated by test_integration.sh",
    "location": "Jakarta",
    "date": "2027-01-01T19:00:00Z",
    "capacity": 100
  }' 2>/dev/null || echo '{"status":"ERROR"}')

assert_ok "$CREATE_EVENT" "Admin buat event"

EVENT_ID=$(jq_get "$CREATE_EVENT" "d.get('data',{}).get('eventId',d.get('data',{}).get('id',''))")
if [[ -z "$EVENT_ID" ]]; then
  fail "eventId tidak ditemukan di response buat event"
  info "Response: $CREATE_EVENT"
  exit 1
fi
info "Event ID: $EVENT_ID"

# Buat kategori VIP
CREATE_CAT=$(curl -sf -X POST "$EVENT_SVC/api/event/v1/admin/$EVENT_ID/create-category" \
  -H "Content-Type: application/json" \
  -H "Authorization: Bearer $ADMIN_TOKEN" \
  -d '{"name":"VIP","price":500000,"capacity":50}' 2>/dev/null \
  || echo '{"status":"ERROR"}')

assert_ok "$CREATE_CAT" "Admin buat kategori VIP"

CATEGORY_ID=$(jq_get "$CREATE_CAT" "d.get('data',{}).get('categoryId',d.get('data',{}).get('id',''))")
if [[ -z "$CATEGORY_ID" ]]; then
  fail "categoryId tidak ditemukan"
  info "Response: $CREATE_CAT"
else
  info "Category ID: $CATEGORY_ID"
fi

# Verifikasi event muncul di public list
LIST_EVENTS=$(curl -sf "$EVENT_SVC/api/event/v1/list" 2>/dev/null || echo '{"status":"ERROR"}')
assert_ok "$LIST_EVENTS" "Public list events"

# ─────────────────────────────────────────────────────────────
# STEP 3: User register + login
# ─────────────────────────────────────────────────────────────
step "3" "User register + login via user-service"

REGISTER=$(curl -sf -X POST "$USER_SVC/auth/register" \
  -H "Content-Type: application/json" \
  -d "{\"email\":\"$USER_EMAIL\",\"password\":\"$USER_PASSWORD\",\"name\":\"Test User\"}" \
  2>/dev/null || echo '{"status":"ERROR"}')

assert_ok "$REGISTER" "User register"

USER_LOGIN=$(curl -sf -X POST "$USER_SVC/auth/login" \
  -H "Content-Type: application/json" \
  -d "{\"email\":\"$USER_EMAIL\",\"password\":\"$USER_PASSWORD\"}" \
  2>/dev/null || echo '{"status":"ERROR"}')

assert_ok "$USER_LOGIN" "User login"

USER_TOKEN=$(jq_get "$USER_LOGIN" "d.get('data',{}).get('authToken','')")
if [[ -z "$USER_TOKEN" ]]; then
  fail "authToken user tidak ditemukan"
  info "Response: $USER_LOGIN"
fi
info "User token prefix: ${USER_TOKEN:0:20}..."

# ─────────────────────────────────────────────────────────────
# STEP 4: User join antrian via queue-service → dapat Access Token
# ─────────────────────────────────────────────────────────────
step "4" "User join antrian (queue-service)"

JOIN_QUEUE=$(curl -sf -X POST "$QUEUE_SVC/api/queue/v1/event/$EVENT_ID/join" \
  -H "Content-Type: application/json" \
  2>/dev/null || echo '{"status":"ERROR"}')

assert_ok "$JOIN_QUEUE" "Join antrian"

QUEUE_TOKEN=$(jq_get "$JOIN_QUEUE" "d.get('data',{}).get('queueToken','')")
ACCESS_TOKEN=$(jq_get "$JOIN_QUEUE" "d.get('data',{}).get('accessToken','')")
info "Queue token: ${QUEUE_TOKEN:0:20}..."

# Jika langsung admit (antrian pendek/kosong), accessToken sudah ada
if [[ -n "$ACCESS_TOKEN" ]]; then
  info "Langsung admit — accessToken sudah tersedia"
else
  info "Menunggu admit dari queue-service (polling status)..."
  # Poll status sampai accessToken ada, max 30 detik
  for i in $(seq 1 6); do
    sleep 5
    STATUS=$(curl -sf "$QUEUE_SVC/api/queue/v1/event/$EVENT_ID/$QUEUE_TOKEN" 2>/dev/null \
      || echo '{"status":"ERROR"}')
    ACCESS_TOKEN=$(jq_get "$STATUS" "d.get('data',{}).get('accessToken','')")
    if [[ -n "$ACCESS_TOKEN" ]]; then
      info "Admitted setelah ${i}x polling (${i}x5s)"
      break
    fi
    info "Polling $i/6 — belum admit..."
  done
fi

if [[ -z "$ACCESS_TOKEN" ]]; then
  fail "accessToken tidak diterima setelah 30 detik — cek queue-service"
  info "Kemungkinan penyebab: queue cap terlalu ketat, atau KAFKA stock.changed belum sampai"
else
  ok "Access Token dari queue-service diterima"
  info "Access token prefix: ${ACCESS_TOKEN:0:20}..."
fi

# ─────────────────────────────────────────────────────────────
# STEP 5: Create booking via booking-service (butuh Access Token)
# ─────────────────────────────────────────────────────────────
step "5" "Create booking (booking-service)"

if [[ -z "$ACCESS_TOKEN" ]] || [[ -z "$CATEGORY_ID" ]]; then
  fail "SKIP create booking — Access Token atau categoryId tidak tersedia"
  BOOKING_ID=""
else
  CREATE_BOOKING=$(curl -sf -X POST "$BOOKING_SVC/api/booking/v1/create" \
    -H "Content-Type: application/json" \
    -H "X-Access-Token: $ACCESS_TOKEN" \
    -d "{
      \"eventId\": \"$EVENT_ID\",
      \"email\": \"$USER_EMAIL\",
      \"items\": [{
        \"categoryId\": \"$CATEGORY_ID\",
        \"attendees\": [{
          \"nik\": \"$TEST_NIK\",
          \"nama\": \"$TEST_NAMA\",
          \"tglLahir\": \"$TEST_TGL_LAHIR\",
          \"namaIbu\": \"$TEST_NAMA_IBU\"
        }]
      }]
    }" 2>/dev/null || echo '{"status":"ERROR"}')

  assert_ok "$CREATE_BOOKING" "Create booking (status HELD)"

  BOOKING_ID=$(jq_get "$CREATE_BOOKING" "d.get('data',{}).get('bookingId','')")
  info "Booking ID: $BOOKING_ID"

  # Verifikasi status HELD
  if [[ -n "$BOOKING_ID" ]]; then
    GET_BOOKING=$(curl -sf "$BOOKING_SVC/api/booking/v1/$BOOKING_ID" \
      -H "X-Access-Token: $ACCESS_TOKEN" 2>/dev/null || echo '{"status":"ERROR"}')
    assert_ok "$GET_BOOKING" "GET booking status"
    BOOKING_STATUS=$(jq_get "$GET_BOOKING" "d.get('data',{}).get('status','')")
    if [[ "$BOOKING_STATUS" == "HELD" ]]; then
      ok "Booking status = HELD ✓"
    else
      fail "Booking status = '$BOOKING_STATUS' (expected HELD)"
    fi
  fi
fi

# ─────────────────────────────────────────────────────────────
# STEP 6: Lihat metode bayar (payment-service)
# ─────────────────────────────────────────────────────────────
step "6" "Lihat metode bayar (payment-service)"

if [[ -z "${BOOKING_ID:-}" ]]; then
  fail "SKIP payment list — tidak ada bookingId"
else
  PAYMENT_METHODS=$(curl -sf "$PAYMENT_SVC/api/payment/v1/booking/$BOOKING_ID" \
    -H "X-Access-Token: $ACCESS_TOKEN" 2>/dev/null || echo '{"status":"ERROR"}')
  assert_ok "$PAYMENT_METHODS" "GET payment methods"
fi

# ─────────────────────────────────────────────────────────────
# STEP 7: Charge pembayaran → dapat snap_token Midtrans
# ─────────────────────────────────────────────────────────────
step "7" "Charge pembayaran Midtrans (payment-service)"

if [[ -z "${BOOKING_ID:-}" ]]; then
  fail "SKIP charge — tidak ada bookingId"
else
  CHARGE=$(curl -sf -X POST "$PAYMENT_SVC/api/payment/v1/charge" \
    -H "Content-Type: application/json" \
    -H "X-Access-Token: $ACCESS_TOKEN" \
    -d "{\"bookingId\":\"$BOOKING_ID\",\"paymentMethod\":\"gopay\"}" \
    2>/dev/null || echo '{"status":"ERROR"}')

  assert_ok "$CHARGE" "Charge pembayaran"

  SNAP_TOKEN=$(jq_get "$CHARGE" "d.get('data',{}).get('snapToken',d.get('data',{}).get('token',''))")
  if [[ -n "$SNAP_TOKEN" ]]; then
    ok "snap_token diterima dari Midtrans sandbox ✓"
    info "snap_token prefix: ${SNAP_TOKEN:0:20}..."
  else
    info "snap_token kosong — mungkin MIDTRANS_SERVER_KEY belum di-set atau sandbox offline"
  fi
fi

# ─────────────────────────────────────────────────────────────
# STEP 8: Simulasi Midtrans callback → status PAID
# ─────────────────────────────────────────────────────────────
step "8" "Simulasi Midtrans callback (payment-service)"

if [[ -z "${BOOKING_ID:-}" ]]; then
  fail "SKIP callback — tidak ada bookingId"
else
  # Midtrans signature = sha512(order_id + status_code + gross_amount + server_key)
  # Untuk test, kirim body yang payment-service terima dan verifikasi
  ORDER_ID="$BOOKING_ID"
  GROSS_AMOUNT="500000.00"
  STATUS_CODE="200"

  CALLBACK=$(curl -sf -X POST "$PAYMENT_SVC/api/payment/v1/callback" \
    -H "Content-Type: application/json" \
    -d "{
      \"order_id\": \"$ORDER_ID\",
      \"transaction_status\": \"settlement\",
      \"fraud_status\": \"accept\",
      \"status_code\": \"$STATUS_CODE\",
      \"gross_amount\": \"$GROSS_AMOUNT\",
      \"payment_type\": \"gopay\",
      \"signature_key\": \"BYPASS_FOR_INTEGRATION_TEST\"
    }" 2>/dev/null || echo '{"status":"ERROR"}')

  # Callback mungkin 200 atau 400 tergantung validasi signature
  CB_STATUS=$(jq_get "$CALLBACK" "d.get('status','?')")
  info "Callback response status: $CB_STATUS"
  if [[ "$CB_STATUS" == "00000" ]]; then
    ok "Callback diterima, booking → PAID"
  else
    info "Callback ditolak (normal jika signature validation aktif di payment-service)"
    info "Untuk test manual: jalankan via Midtrans sandbox webhook simulator"
  fi
fi

# ─────────────────────────────────────────────────────────────
# STEP 9: Ticket history via user-service
# ─────────────────────────────────────────────────────────────
step "9" "Ticket history (user-service)"

if [[ -z "$USER_TOKEN" ]]; then
  fail "SKIP ticket-history — user tidak login"
else
  HISTORY=$(curl -sf "$USER_SVC/api/user/v1/ticket-history" \
    -H "Authorization: Bearer $USER_TOKEN" 2>/dev/null \
    || echo '{"status":"ERROR"}')

  assert_ok "$HISTORY" "GET ticket-history"

  HISTORY_COUNT=$(jq_get "$HISTORY" "len(d.get('data',[]))" 2>/dev/null || echo "0")
  info "Jumlah tiket di history: $HISTORY_COUNT"
fi

# ─────────────────────────────────────────────────────────────
# STEP 10: Negative test — token expired ditolak booking-service
# ─────────────────────────────────────────────────────────────
step "10" "Negative test: token expired → ditolak (INT-4)"

# Generate token dengan bookingTtlExpiresAt di masa lalu menggunakan gen_demo_token.go
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if command -v go &>/dev/null && [[ -f "$SCRIPT_DIR/gen_demo_token.go" ]]; then
  EXPIRED_TOKEN=$(cd "$SCRIPT_DIR" && go run gen_demo_token.go \
    --event-id "$EVENT_ID" --expires-at 1 2>/dev/null || echo "")

  if [[ -n "$EXPIRED_TOKEN" ]] && [[ "${CATEGORY_ID:-}" != "" ]]; then
    EXPIRED_RESP=$(curl -sf -X POST "$BOOKING_SVC/api/booking/v1/create" \
      -H "Content-Type: application/json" \
      -H "X-Access-Token: $EXPIRED_TOKEN" \
      -d "{\"eventId\":\"$EVENT_ID\",\"email\":\"neg@test.com\",
           \"items\":[{\"categoryId\":\"$CATEGORY_ID\",
           \"attendees\":[{\"nik\":\"$TEST_NIK\",\"nama\":\"$TEST_NAMA\",
           \"tglLahir\":\"$TEST_TGL_LAHIR\",\"namaIbu\":\"$TEST_NAMA_IBU\"}]}]}" \
      2>/dev/null || echo '{"status":"ERROR"}')

    EXPIRED_STATUS=$(jq_get "$EXPIRED_RESP" "d.get('status','?')")
    if [[ "$EXPIRED_STATUS" != "00000" ]]; then
      ok "Expired token ditolak (status=$EXPIRED_STATUS) ✓"
    else
      fail "Expired token DITERIMA (seharusnya ditolak) — cek validasi INT-4"
    fi
  else
    info "SKIP expired token test — gen_demo_token.go tidak support --expires-at atau categoryId kosong"
  fi
else
  info "SKIP expired token test — go tidak tersedia atau gen_demo_token.go tidak ada"
fi

# ─────────────────────────────────────────────────────────────
# Ringkasan
# ─────────────────────────────────────────────────────────────
echo ""
echo -e "${BOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${RESET}"
echo -e "${BOLD}  INTEGRATION TEST SELESAI${RESET}"
echo -e "${BOLD}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${RESET}"
echo -e "  ${GREEN}PASS: $PASS${RESET}  ${RED}FAIL: $FAIL${RESET}"
echo ""

if [[ $FAIL -gt 0 ]]; then
  echo -e "${RED}${BOLD}Ada $FAIL test gagal. Cek output di atas untuk detail.${RESET}"
  echo ""
  echo "Tips debug:"
  echo "  - Pastikan semua 6 service running (lihat preflight di atas)"
  echo "  - Cek USER_JWT_SECRET sama antara user-service dan event-service"
  echo "  - Cek ACCESS_TOKEN_SECRET sama antara queue-service dan booking-service"
  echo "  - Cek DUKCAPIL_BASE_URL di booking-service menunjuk ke dukcapil-mock BE-1"
  echo "  - Untuk INT-2/INT-3: set env ADMIN_EMAIL, ADMIN_PASSWORD, TEST_NIK sesuai seed BE-1"
  exit 1
else
  echo -e "${GREEN}${BOLD}Semua test PASS! Integrasi BE-1 <-> BE-2 berjalan.${RESET}"
  exit 0
fi
